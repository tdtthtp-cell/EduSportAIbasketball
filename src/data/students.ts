import { StudentProfile, HealthStatus } from '../types';

export function calculateBmiValue(heightCm: number, weightKg: number): number {
  if (!heightCm || heightCm <= 0 || !weightKg || weightKg <= 0) return 0;
  const heightM = heightCm / 100;
  return Math.round((weightKg / (heightM * heightM)) * 10) / 10;
}

export function classifyBmiCategory(bmi: number): HealthStatus {
  if (bmi < 18.5) return 'underweight';
  if (bmi >= 23.0) return 'overweight';
  return 'standard';
}

